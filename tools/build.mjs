// Dead Pixel build helper (no dependencies).
//   node tools/build.mjs          writes public/js/unity-script.js from unity/Editor/DeadPixelSheetImporter.cs
//   node tools/build.mjs --single  also writes dist/deadpixel.html: the whole app in one file (CSS and JS inlined)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cs = readFileSync(join(root, 'unity/Editor/DeadPixelSheetImporter.cs'), 'utf8');
writeFileSync(join(root, 'public/js/unity-script.js'),
  '/* Generated by tools/build.mjs from unity/Editor/DeadPixelSheetImporter.cs. Do not edit. */\n' +
  '(function (root) { (root.DP || (root.DP = {})).UNITY_SCRIPT = ' + JSON.stringify(cs) + '; })(typeof window !== "undefined" ? window : globalThis);\n');
console.log('wrote public/js/unity-script.js');

if (process.argv.includes('--single')) {
  let html = readFileSync(join(root, 'public/index.html'), 'utf8');
  html = html.replace(/<link rel="stylesheet" href="(css\/[^"]+)">/g, (_, p) => '<style>\n' + readFileSync(join(root, 'public', p), 'utf8') + '\n</style>');
  html = html.replace(/<script src="(js\/[^"]+)"><\/script>/g, (_, p) => '<script>\n' + readFileSync(join(root, 'public', p), 'utf8').replace(/<\/script/gi, '<\\/script') + '\n</script>');
  const dataUri = (p) => {
    const buf = readFileSync(join(root, 'public', p));
    const type = p.endsWith('.svg') ? 'image/svg+xml' : p.endsWith('.ico') ? 'image/x-icon' : 'image/png';
    return 'data:' + type + ';base64,' + buf.toString('base64');
  };
  html = html.replace(/(href|src)="((?:favicon|icons\/)[^"]+)"/g, (_, a, p) => a + '="' + dataUri(p) + '"');
  mkdirSync(join(root, 'dist'), { recursive: true });
  const out = process.argv[process.argv.indexOf('--single') + 1];
  const dest = out && !out.startsWith('--') ? out : join(root, 'dist/deadpixel.html');
  writeFileSync(dest, html);
  console.log('wrote ' + dest + ' (' + Math.round(html.length / 1024) + ' KB)');
}
